import "@testing-library/jest-dom/vitest";

// jsdom does not provide Web Storage in this project's configuration, and the
// demo ledger (src/lib/demo.ts) persists to localStorage. Install a minimal
// in-memory implementation so browser-side state can be exercised in tests.
if (!window.localStorage) {
  const store = new Map<string, string>();
  Object.defineProperty(window, "localStorage", {
    configurable: true,
    value: {
      get length() {
        return store.size;
      },
      clear: () => store.clear(),
      getItem: (key: string) => store.get(key) ?? null,
      key: (index: number) => [...store.keys()][index] ?? null,
      removeItem: (key: string) => void store.delete(key),
      setItem: (key: string, value: string) => void store.set(key, String(value)),
    } satisfies Storage,
  });
}

